-- ===== منع تكرار رقم الإيصال نهائياً =====
-- يُنشأ القيد فقط إذا لم توجد تكرارات حالياً. إن وُجدت تكرارات سيظهر تنبيه بدل الفشل.
do $$
begin
  if exists (select 1 from public.receipts group by receipt_no having count(*) > 1) then
    raise notice 'يوجد أرقام إيصالات مكررة. شغّل: select receipt_no, count(*) from public.receipts group by receipt_no having count(*)>1; ثم صحّحها وأعد تشغيل الملف.';
  else
    create unique index if not exists receipts_receipt_no_unique on public.receipts(receipt_no);
  end if;
end $$;

-- ===== المشرفون (رقم هاتف + كلمة مرور؛ إضافة محتوى غير مالي فقط) =====
create table if not exists public.app_supervisors (
  email text primary key,
  created_at timestamptz not null default now()
);
alter table public.app_supervisors add column if not exists phone text;
alter table public.app_supervisors enable row level security;

drop policy if exists "admin manage supervisors" on public.app_supervisors;
create policy "admin manage supervisors" on public.app_supervisors for all to authenticated
using ((auth.jwt() ->> 'email') = 'moi25rf@gmail.com')
with check ((auth.jwt() ->> 'email') = 'moi25rf@gmail.com');

drop policy if exists "supervisor read own role" on public.app_supervisors;
create policy "supervisor read own role" on public.app_supervisors for select to authenticated
using (lower(email) = lower(auth.jwt() ->> 'email'));

create table if not exists public.app_supervisor_entries (
  id bigint generated by default as identity primary key,
  title text not null,
  body text not null default '',
  created_by uuid not null references auth.users(id),
  created_at timestamptz not null default now()
);
alter table public.app_supervisor_entries enable row level security;

drop policy if exists "public read supervisor entries" on public.app_supervisor_entries;
create policy "public read supervisor entries" on public.app_supervisor_entries for select to anon, authenticated using (true);

drop policy if exists "supervisors append entries" on public.app_supervisor_entries;
create policy "supervisors append entries" on public.app_supervisor_entries for insert to authenticated
with check (created_by = auth.uid() and exists (
  select 1 from public.app_supervisors s where lower(s.email) = lower(auth.jwt() ->> 'email')
));

drop policy if exists "admin delete supervisor entries" on public.app_supervisor_entries;
create policy "admin delete supervisor entries" on public.app_supervisor_entries for delete to authenticated
using ((auth.jwt() ->> 'email') = 'moi25rf@gmail.com');
